def dia_semana(numero):
    if(numero == 1):
        return "Lunes";
    elif(numero == 2):
        return "Martes";
    elif(numero == 3):
        return "Miércoles";
    elif(numero == 4):
        return "Jueves";
    elif(numero == 5):
        return "Viernes";
    elif(numero == 6):
        return "Sábado";
    elif(numero == 7):
        return "Domingo";
    else:
        return "Día no válido";